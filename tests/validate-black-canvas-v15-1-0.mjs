#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
const read = file => fs.readFileSync(file,"utf8");
const css = read("black-canvas-v15-1-0.css");
const liquid = read("liquid-glass-v15.css");
const index = read("index.html");
const offline = read("offline.html");
const manifest = JSON.parse(read("manifest.webmanifest"));
const version = JSON.parse(read("version.json"));
const worker = read("sw.js");
assert.match(css,/--bg:#000000/);
assert.match(css,/--primary:#173e76/);
assert.match(css,/html\[data-theme="light"\]/);
assert.match(css,/html\[data-theme="dark"\]/);
assert.match(css,/--nav-active-bg:#173e76/);
assert.match(css,/\.button-paid \{[\s\S]*background:var\(--primary\) !important;[\s\S]*border-color:var\(--primary\) !important;/);
assert.match(css,/\.button-paid:hover \{[\s\S]*background:var\(--primary-dark\) !important;/);
