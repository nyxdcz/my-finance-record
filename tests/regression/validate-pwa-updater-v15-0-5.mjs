#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
const index = fs.readFileSync("index.html", "utf8");
const worker = fs.readFileSync("sw.js", "utf8");
const updater = fs.readFileSync("pwa-update-v15-0-5.js", "utf8");
const desktopUx = fs.readFileSync("desktop-ux-v15-2-0.css", "utf8");
const version = JSON.parse(fs.readFileSync("version.json", "utf8"));
assert.equal(version.version, "15.2.10");
assert.equal(version.cacheVersion, "finance-v15-20260820-sidebar-icons-r46");
assert.match(index, /const APP_CACHE_VERSION = "finance-v15-20260820-sidebar-icons-r46";/);
assert.match(index, /FinancePwaUpdate\.shellCacheName\(APP_CACHE_VERSION\)/);
assert.match(index, /FinancePwaUpdate\.clearFinanceCaches\(\)/);
assert.match(index, /registration\.scope === financeScope/);
assert.match(index, /FinancePwaUpdate\.serviceWorkerUrl\(APP_VERSION, APP_CACHE_VERSION\)/);
assert.match(index, /FinancePwaUpdate\.updateState\(remote, APP_VERSION, APP_CACHE_VERSION\)/);
assert.match(index, /let serviceWorkerControlled = Boolean\(navigator\.serviceWorker\.controller\);/);
assert.match(index, /if \(serviceWorkerControlled\) location\.reload\(\);/);
assert.doesNotMatch(index, /finance-v\(\?:12\|13\)/);
assert.match(updater, /const FINANCE_CACHE_PATTERN = \/\^finance-v\\d\+-\//);
assert.match(updater, /const LEGACY_INDEX_CACHE = "finance-v15-20260816-mobile-ui-ux-r32";/);
assert.match(updater, /const CURRENT_CACHE_VERSION = "finance-v15-20260820-sidebar-icons-r46";/);
assert.match(updater, /normalizeCacheVersion/);
assert.match(updater, /serviceWorkerUrl\(version, cacheVersion\)/);
assert.match(updater, /cacheChanged:Boolean\(remote\?\.cacheVersion && remote\.cacheVersion !== normalizedCache\)/);
assert.match(updater, /async clearFinanceCaches\(\)/);
assert.doesNotMatch(updater, /installCashFlowStyles|cashFlowLayoutV1522/, "Cash Flow presentation must not be injected by the PWA updater");
assert.match(updater, /function upgradeCashFlowLayout\(\)/, "Cash Flow DOM summary upgrade behavior must remain in place");
assert.match(desktopUx, /\.cash-flow-chart-main \.chart-legend\{[\s\S]*margin:6px 0 0;[\s\S]*padding-top:6px;[\s\S]*border-top:1px solid var\(--line\);/, "Static CSS must own the current Cash Flow legend geometry");
assert.match(desktopUx, /\.cash-flow-summary-panel\{[\s\S]*padding:10px;/, "Static CSS must own the current Cash Flow summary padding");
assert.match(worker, /const APP_VERSION = "15\.2\.10";/);
assert.match(worker, /finance-v15-20260820-sidebar-icons-r46/);
assert.match(worker, /networkFirstCriticalAsset/);
assert.match(worker, /url\.pathname\.endsWith\("privacy-lock\.js"\) \|\| url\.pathname\.endsWith\("cloud-sync-lifecycle\.js"\)/);
assert.match(worker, /pwa-update-v15-0-5\.js\?v=15\.2\.10-release1/);
assert.match(worker, /ui-icon-alignment-v15-0-5\.css\?v=15\.2\.9-ui2/);
assert.match(worker, /mobile-v14-0-23\.css/);
assert.match(worker, /budget-planning\.css/);
assert.match(worker, /black-canvas-v15-1-0\.css/);
console.log("V15.2.10 PWA updater regression passed with Application Help extraction cache refresh.");
