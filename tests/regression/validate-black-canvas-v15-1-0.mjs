#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
const read = file => fs.readFileSync(file,"utf8");
const css = read("black-canvas-v15-1-0.css");
const liquid = read("liquid-glass-v15.css");
const index = read("index.html");
const offline = read("offline.html");
const manifest = JSON.parse(read("manifest.webmanifest"));
const version = JSON.parse(read("version.json"));
const worker = read("sw.js");
assert.match(css,/html\[data-theme="light"\][\s\S]*--bg:#efefef/);
assert.match(css,/html\[data-theme="dark"\][\s\S]*--bg:#000000/);
assert.match(css,/--primary:#173e76/);
assert.match(css,/--nav-active-bg:#173e76/);
assert.match(css,/\.button-paid \{[\s\S]*background:var\(--primary\) !important;[\s\S]*border-color:var\(--primary\) !important;/);
assert.match(css,/\.button-paid:hover \{[\s\S]*background:var\(--primary-dark\) !important;/);
assert.match(css,/html\[data-theme="light"\] body #money #availableMoneySection \.account-card \.account-card-main \.account-card-label span \{[\s\S]*color:var\(--text\) !important;/);
assert.doesNotMatch(css,/html\[data-theme="light"\] body #money #availableMoneySection[\s\S]*\.account-card-label small/);
assert.doesNotMatch(css,/html\[data-theme="dark"\] body #money #availableMoneySection \.account-card \.account-card-main \.account-card-label/);
assert.match(css,/#money \.period-card \{[\s\S]*border-radius:9px !important;[\s\S]*#money \.period-card \.period-header,[\s\S]*#money \.period-card \.record-row \{[\s\S]*border-radius:9px !important;/);
assert.match(liquid,/--liquid-glass-active:rgba\(23,62,118,/);
assert.match(liquid,/html\[data-theme="light"\][\s\S]*--liquid-glass-surface:rgba\(255,255,255,.82\)/);
assert.match(liquid,/html\[data-theme="light"\][\s\S]*--nav:#ffffff/);
assert.match(liquid,/html\[data-theme="light"\] \.sidebar \.nav-button\.active[\s\S]*color:#ffffff/);
assert.match(index,/<meta name="theme-color" content="#173e76">/);
assert.match(index,/black-canvas-v15-1-0\.css\?v=15\.1\.0-light1/);
assert.equal(manifest.background_color,"#000000");
assert.equal(manifest.theme_color,"#173e76");
assert.match(offline,/background:#000000/);
assert.equal(version.version,"15.2.24");
assert.equal(version.cacheVersion,"finance-v15-20260822-compact-expense-collapse-r60");
assert.match(worker,/black-canvas-v15-1-0\.css\?v=15\.1\.0-light1/);
console.log("V15.2.18 light/dark palette regression passed under V15.2.24 with only account names matching the balance color in light mode while account types keep their original color.");
