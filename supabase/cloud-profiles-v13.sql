create or replace function public.finance_v3_remove_member(p_profile_id uuid,p_member_user_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_role text;
begin
  v_role:=public.finance_v3_require_member(p_profile_id,false);
  if v_role<>'owner' then raise exception 'owner_required'; end if;
  delete from public.finance_v3_members where profile_id=p_profile_id and user_id=p_member_user_id and role<>'owner';
  if not found then raise exception 'member_not_found_or_owner'; end if;
  update public.finance_v3_devices set revoked_at=coalesce(revoked_at,now()),revoked_by_user=auth.uid()
   where profile_id=p_profile_id and user_id=p_member_user_id;
  return jsonb_build_object('status','removed','user_id',p_member_user_id);
end;
$$;

create or replace function public.finance_v3_register_device(
  p_profile_id uuid,p_device_id text,p_device_name text,p_platform text,p_app_version text,p_app_version_code integer,p_last_pull_audit_id bigint default 0
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_role text; v_device public.finance_v3_devices%rowtype;
begin
  v_role:=public.finance_v3_require_member(p_profile_id,false);
  if coalesce(length(trim(p_device_id)),0)=0 then raise exception 'device_id_required'; end if;
  select * into v_device from public.finance_v3_devices where profile_id=p_profile_id and user_id=v_uid and device_id=p_device_id;
  if found and v_device.revoked_at is not null then return jsonb_build_object('status','revoked','revoked_at',v_device.revoked_at); end if;
  insert into public.finance_v3_devices(profile_id,user_id,device_id,device_name,platform,app_version,app_version_code,cloud_schema_version,last_pull_audit_id,last_seen_at)
  values(p_profile_id,v_uid,left(trim(p_device_id),160),left(coalesce(nullif(trim(p_device_name),''),'Device'),80),left(coalesce(p_platform,''),300),left(coalesce(p_app_version,''),40),greatest(coalesce(p_app_version_code,0),0),3,greatest(coalesce(p_last_pull_audit_id,0),0),now())
  on conflict(profile_id,user_id,device_id) do update set device_name=excluded.device_name,platform=excluded.platform,app_version=excluded.app_version,app_version_code=excluded.app_version_code,cloud_schema_version=3,last_seen_at=now(),last_pull_audit_id=greatest(public.finance_v3_devices.last_pull_audit_id,excluded.last_pull_audit_id);
  return jsonb_build_object('status','active','device_id',p_device_id,'role',v_role);
end;
$$;

create or replace function public.finance_v3_revoke_device(p_profile_id uuid,p_user_id uuid,p_device_id text,p_revoked_by_device text)
returns jsonb
