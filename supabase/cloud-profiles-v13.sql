$$;

create or replace function public.finance_v3_snapshot(p_profile_id uuid,p_device_id text)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_role text; v_profile public.finance_v3_profiles%rowtype; v_device public.finance_v3_devices%rowtype; v_records jsonb;
begin
  v_role:=public.finance_v3_require_member(p_profile_id,false);
  select * into v_device from public.finance_v3_devices where profile_id=p_profile_id and user_id=v_uid and device_id=p_device_id;
  if found and v_device.revoked_at is not null then return jsonb_build_object('status','revoked','revoked_at',v_device.revoked_at); end if;
  select * into v_profile from public.finance_v3_profiles where id=p_profile_id;
  select coalesce(jsonb_agg(jsonb_build_object(
    'collection',collection,'record_id',record_id,'payload',payload,'sort_index',sort_index,'revision',revision,
    'deleted_at',deleted_at,'updated_at',updated_at,'updated_by_user',updated_by_user,'updated_by_device',updated_by_device,
    'app_version',app_version,'app_version_code',app_version_code,'min_writer_version_code',min_writer_version_code
  ) order by collection,sort_index,record_id),'[]'::jsonb) into v_records
  from public.finance_v3_records where profile_id=p_profile_id;
  return jsonb_build_object('status','ok','profile_id',p_profile_id,'role',v_role,'records',v_records,'latest_audit_id',v_profile.current_audit_id,
    'cloud_schema_version',3,'min_app_version_code',v_profile.min_app_version_code,'encryption_salt',v_profile.encryption_salt,'encryption_check',v_profile.encryption_check,'kdf_iterations',v_profile.kdf_iterations);
end;
$$;

create or replace function public.finance_v3_pull(p_profile_id uuid,p_after_audit_id bigint,p_limit integer,p_device_id text)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_role text; v_device public.finance_v3_devices%rowtype; v_events jsonb; v_latest bigint; v_limit integer:=greatest(1,least(coalesce(p_limit,250),500)); v_more boolean;
begin
  v_role:=public.finance_v3_require_member(p_profile_id,false);
  select * into v_device from public.finance_v3_devices where profile_id=p_profile_id and user_id=v_uid and device_id=p_device_id;
  if not found then return jsonb_build_object('status','device_missing'); end if;
  if v_device.revoked_at is not null then return jsonb_build_object('status','revoked','revoked_at',v_device.revoked_at); end if;
  with selected as (
    select * from public.finance_v3_audit where profile_id=p_profile_id and id>greatest(coalesce(p_after_audit_id,0),0) order by id limit v_limit+1
  ), page as (select * from selected order by id limit v_limit)
  select coalesce(jsonb_agg(jsonb_build_object('id',id,'collection',collection,'record_id',record_id,'payload',payload,'sort_index',sort_index,'revision',revision,'deleted_at',deleted_at,'updated_at',created_at,'updated_by_user',actor_user_id,'updated_by_device',device_id,'app_version',app_version,'app_version_code',app_version_code) order by id),'[]'::jsonb),
    coalesce(max(id),greatest(coalesce(p_after_audit_id,0),0)),(select count(*)>v_limit from selected)
  into v_events,v_latest,v_more from page;
  update public.finance_v3_devices set last_seen_at=now(),last_sync_at=now(),last_pull_audit_id=greatest(last_pull_audit_id,v_latest) where profile_id=p_profile_id and user_id=v_uid and device_id=p_device_id;
  return jsonb_build_object('status','ok','events',v_events,'latest_audit_id',v_latest,'has_more',coalesce(v_more,false),'role',v_role);
end;
$$;

create or replace function public.finance_v3_commit_batch(
  p_profile_id uuid,p_batch_id text,p_device_id text,p_app_version text,p_app_version_code integer,p_changes jsonb,p_migrated_from_v2 boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_uid uuid:=auth.uid(); v_role text; v_profile public.finance_v3_profiles%rowtype; v_existing public.finance_v3_records%rowtype;
  v_change jsonb; v_conflicts jsonb:='[]'::jsonb; v_results jsonb:='[]'::jsonb; v_result jsonb;
  v_collection text; v_record_id text; v_payload jsonb; v_expected bigint; v_sort integer; v_deleted boolean; v_revision bigint; v_deleted_at timestamptz; v_audit_id bigint; v_latest bigint:=0; v_min_writer integer;
begin
  v_role:=public.finance_v3_require_member(p_profile_id,true);
  if coalesce(length(trim(p_batch_id)),0)=0 then raise exception 'batch_id_required'; end if;
  if jsonb_typeof(p_changes)<>'array' then raise exception 'changes_must_be_array'; end if;
  if jsonb_array_length(p_changes)>500 then raise exception 'too_many_changes'; end if;
  select * into v_profile from public.finance_v3_profiles where id=p_profile_id for update;
  if p_app_version_code<v_profile.min_app_version_code then return jsonb_build_object('status','upgrade_required','min_app_version_code',v_profile.min_app_version_code); end if;
  if exists(select 1 from public.finance_v3_devices where profile_id=p_profile_id and user_id=v_uid and device_id=p_device_id and revoked_at is not null) then return jsonb_build_object('status','revoked'); end if;
  select result into v_result from public.finance_v3_batches where profile_id=p_profile_id and batch_id=p_batch_id;
  if found then return v_result; end if;
  insert into public.finance_v3_batches(profile_id,batch_id,actor_user_id,device_id) values(p_profile_id,left(p_batch_id,180),v_uid,left(p_device_id,160));

  for v_change in select value from jsonb_array_elements(p_changes) loop
    v_collection:=left(coalesce(v_change->>'collection',''),60); v_record_id:=left(coalesce(v_change->>'record_id',''),240);
    v_expected:=greatest(coalesce((v_change->>'base_revision')::bigint,0),0);
    v_min_writer:=greatest(coalesce((v_change->>'min_writer_version_code')::integer,p_app_version_code),130000);
    if v_collection='' or v_record_id='' then raise exception 'record_identity_required'; end if;
    if not coalesce((v_change->'payload') ? '__financeEncrypted',false) then raise exception 'encrypted_payload_required'; end if;
    select * into v_existing from public.finance_v3_records where profile_id=p_profile_id and collection=v_collection and record_id=v_record_id;
    if found and v_existing.min_writer_version_code>p_app_version_code then
      v_conflicts:=v_conflicts||jsonb_build_array(jsonb_build_object('collection',v_collection,'record_id',v_record_id,'reason','record_requires_newer_app','remote_revision',v_existing.revision,'remote_payload',v_existing.payload,'remote_deleted_at',v_existing.deleted_at));
    elsif found and v_existing.revision<>v_expected then
      v_conflicts:=v_conflicts||jsonb_build_array(jsonb_build_object('collection',v_collection,'record_id',v_record_id,'reason','revision_changed','expected_revision',v_expected,'remote_revision',v_existing.revision,'remote_payload',v_existing.payload,'remote_deleted_at',v_existing.deleted_at));
    elsif not found and v_expected<>0 then
      v_conflicts:=v_conflicts||jsonb_build_array(jsonb_build_object('collection',v_collection,'record_id',v_record_id,'reason','record_missing','expected_revision',v_expected,'remote_revision',0));
    end if;
  end loop;
  if jsonb_array_length(v_conflicts)>0 then
    v_result:=jsonb_build_object('status','conflict','conflicts',v_conflicts,'batch_id',p_batch_id);
    update public.finance_v3_batches set status='conflict',result=v_result,committed_at=now() where profile_id=p_profile_id and batch_id=p_batch_id;
    return v_result;
  end if;

  for v_change in select value from jsonb_array_elements(p_changes) loop
    v_collection:=left(v_change->>'collection',60); v_record_id:=left(v_change->>'record_id',240); v_payload:=v_change->'payload';
    v_sort:=coalesce((v_change->>'sort_index')::integer,0); v_deleted:=coalesce((v_change->>'deleted')::boolean,false); v_min_writer:=greatest(coalesce((v_change->>'min_writer_version_code')::integer,p_app_version_code),130000);
    select * into v_existing from public.finance_v3_records where profile_id=p_profile_id and collection=v_collection and record_id=v_record_id;
    v_revision:=case when found then v_existing.revision+1 else 1 end; v_deleted_at:=case when v_deleted then now() else null end;
    insert into public.finance_v3_records(profile_id,collection,record_id,payload,sort_index,revision,deleted_at,updated_at,updated_by_user,updated_by_device,app_version,app_version_code,min_writer_version_code,finance_schema_version)
    values(p_profile_id,v_collection,v_record_id,v_payload,v_sort,v_revision,v_deleted_at,now(),v_uid,left(p_device_id,160),left(coalesce(p_app_version,''),40),coalesce(p_app_version_code,0),v_min_writer,12)
    on conflict(profile_id,collection,record_id) do update set payload=excluded.payload,sort_index=excluded.sort_index,revision=excluded.revision,deleted_at=excluded.deleted_at,updated_at=excluded.updated_at,updated_by_user=excluded.updated_by_user,updated_by_device=excluded.updated_by_device,app_version=excluded.app_version,app_version_code=excluded.app_version_code,min_writer_version_code=greatest(public.finance_v3_records.min_writer_version_code,excluded.min_writer_version_code),finance_schema_version=12;
    insert into public.finance_v3_audit(profile_id,actor_user_id,batch_id,collection,record_id,action,revision,payload,sort_index,deleted_at,device_id,app_version,app_version_code)
    values(p_profile_id,v_uid,left(p_batch_id,180),v_collection,v_record_id,case when v_deleted then 'delete' else 'upsert' end,v_revision,v_payload,v_sort,v_deleted_at,left(p_device_id,160),left(coalesce(p_app_version,''),40),coalesce(p_app_version_code,0)) returning id into v_audit_id;
    v_latest:=greatest(v_latest,v_audit_id);
    v_results:=v_results||jsonb_build_array(jsonb_build_object('collection',v_collection,'record_id',v_record_id,'revision',v_revision,'payload',v_payload,'sort_index',v_sort,'deleted_at',v_deleted_at,'audit_id',v_audit_id,'app_version',p_app_version,'app_version_code',p_app_version_code));
  end loop;
  update public.finance_v3_profiles set current_audit_id=greatest(current_audit_id,v_latest),updated_at=now(),min_app_version_code=greatest(min_app_version_code,130000) where id=p_profile_id;
  update public.finance_v3_devices set last_seen_at=now(),last_sync_at=now(),last_push_at=now(),app_version=left(coalesce(p_app_version,''),40),app_version_code=coalesce(p_app_version_code,0),cloud_schema_version=3 where profile_id=p_profile_id and user_id=v_uid and device_id=p_device_id;
  v_result:=jsonb_build_object('status','committed','batch_id',p_batch_id,'records',v_results,'latest_audit_id',v_latest,'role',v_role,'migrated_from_v2',coalesce(p_migrated_from_v2,false));
  update public.finance_v3_batches set status='committed',result=v_result,committed_at=now() where profile_id=p_profile_id and batch_id=p_batch_id;
  return v_result;
end;
$$;

create or replace function public.finance_v3_commit_financial_operations(
  p_profile_id uuid,p_batch_id text,p_operations jsonb,p_device_id text,p_app_version text,p_app_version_code integer,p_changes jsonb
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_result jsonb; v_operation jsonb; v_type text;
begin
  perform public.finance_v3_require_member(p_profile_id,true);
  if jsonb_typeof(p_operations)<>'array' then raise exception 'operations_must_be_array'; end if;
  for v_operation in select value from jsonb_array_elements(p_operations) loop
    v_type:=coalesce(v_operation->>'operation_type','');
    if v_type not in ('expense_payment','gym_auto_payment','expense_payment_restore') then raise exception 'invalid_financial_operation'; end if;
  end loop;
  v_result:=public.finance_v3_commit_batch(p_profile_id,p_batch_id,p_device_id,p_app_version,p_app_version_code,p_changes,false);
  if v_result->>'status'='committed' then
    for v_operation in select value from jsonb_array_elements(p_operations) loop
      insert into public.finance_v3_payment_operations(profile_id,operation_id,expense_id,operation_type,actor_user_id,account_name,amount,device_id,app_version,payload)
      values(p_profile_id,left(v_operation->>'operation_id',180),left(v_operation->>'expense_id',180),v_operation->>'operation_type',v_uid,left(coalesce(v_operation->>'account_name',''),120),greatest(coalesce((v_operation->>'amount')::numeric,0),0),left(p_device_id,160),left(p_app_version,40),jsonb_build_object('cloud_schema_version',3,'batch_id',p_batch_id))
      on conflict(profile_id,operation_id,expense_id,operation_type) do nothing;
    end loop;
  end if;
  return v_result;
end;
$$;

create or replace function public.finance_v3_create_restore_point(p_profile_id uuid,p_label text,p_encrypted_snapshot jsonb,p_summary jsonb default '{}'::jsonb)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_id uuid; v_record_id text;
begin
  perform public.finance_v3_require_member(p_profile_id,true);
  if not coalesce(p_encrypted_snapshot ? '__financeEncrypted',false) then raise exception 'encrypted_snapshot_required'; end if;
  v_record_id:=coalesce(nullif(split_part(p_encrypted_snapshot->>'aad','|',4),''),'restore-point');
  insert into public.finance_v3_restore_points(profile_id,label,encrypted_snapshot,encryption_record_id,summary,created_by)
  values(p_profile_id,left(coalesce(nullif(trim(p_label),''),'Restore point'),120),p_encrypted_snapshot,left(v_record_id,300),coalesce(p_summary,'{}'::jsonb),v_uid)
  returning id into v_id;
  return jsonb_build_object('status','created','restore_point_id',v_id);
end;
$$;

create or replace function public.finance_v3_list_restore_points(p_profile_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_points jsonb;
begin
  perform public.finance_v3_require_member(p_profile_id,false);
  select coalesce(jsonb_agg(jsonb_build_object('id',r.id,'label',r.label,'summary',r.summary,'created_at',r.created_at,'created_by',r.created_by,'created_by_email',u.email) order by r.created_at desc),'[]'::jsonb)
  into v_points from public.finance_v3_restore_points r join auth.users u on u.id=r.created_by where r.profile_id=p_profile_id;
  return jsonb_build_object('restore_points',v_points);
end;
$$;

create or replace function public.finance_v3_get_restore_point(p_profile_id uuid,p_restore_point_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_point public.finance_v3_restore_points%rowtype;
begin
  perform public.finance_v3_require_member(p_profile_id,false);
  select * into v_point from public.finance_v3_restore_points where profile_id=p_profile_id and id=p_restore_point_id;
  if not found then raise exception 'restore_point_not_found'; end if;
  return jsonb_build_object('id',v_point.id,'label',v_point.label,'encrypted_snapshot',v_point.encrypted_snapshot,'encryption_record_id',v_point.encryption_record_id,'summary',v_point.summary,'created_at',v_point.created_at);
end;
$$;

-- RLS: direct browser writes remain blocked. Mutations occur through security-definer RPCs.
do $$
declare t text;
begin
  foreach t in array array['finance_v3_profiles','finance_v3_members','finance_v3_records','finance_v3_batches','finance_v3_audit','finance_v3_devices','finance_v3_payment_operations','finance_v3_invites','finance_v3_restore_points'] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('alter table public.%I force row level security',t);
    execute format('revoke all on public.%I from anon',t);
    execute format('revoke all on public.%I from authenticated',t);
  end loop;
end $$;

-- Read policies are profile-membership scoped. Sensitive invite tokens remain RPC-only.
grant select on public.finance_v3_profiles,public.finance_v3_members,public.finance_v3_records,public.finance_v3_batches,public.finance_v3_audit,public.finance_v3_devices,public.finance_v3_payment_operations,public.finance_v3_restore_points to authenticated;

drop policy if exists "finance v3 profiles member read" on public.finance_v3_profiles;
create policy "finance v3 profiles member read" on public.finance_v3_profiles for select to authenticated using (public.finance_v3_role(id) is not null);
drop policy if exists "finance v3 members member read" on public.finance_v3_members;
create policy "finance v3 members member read" on public.finance_v3_members for select to authenticated using (public.finance_v3_role(profile_id) is not null);
drop policy if exists "finance v3 records member read" on public.finance_v3_records;
create policy "finance v3 records member read" on public.finance_v3_records for select to authenticated using (public.finance_v3_role(profile_id) is not null);
drop policy if exists "finance v3 batches member read" on public.finance_v3_batches;
create policy "finance v3 batches member read" on public.finance_v3_batches for select to authenticated using (public.finance_v3_role(profile_id) is not null);
drop policy if exists "finance v3 audit member read" on public.finance_v3_audit;
create policy "finance v3 audit member read" on public.finance_v3_audit for select to authenticated using (public.finance_v3_role(profile_id) is not null);
drop policy if exists "finance v3 devices member read" on public.finance_v3_devices;
create policy "finance v3 devices member read" on public.finance_v3_devices for select to authenticated using (public.finance_v3_role(profile_id) is not null);
drop policy if exists "finance v3 payments member read" on public.finance_v3_payment_operations;
