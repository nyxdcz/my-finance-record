-- My Finance Records V13.0.0 · Cloud Schema V3
-- Profile-scoped encrypted record sync, household membership roles, immutable audit,
-- invitation codes, device revocation, and encrypted cloud restore points.
--
-- Run after the V12.21.0 Cloud Schema V2 migration. V2 tables are intentionally
-- preserved for rollback and are not modified by this migration.

begin;

create table if not exists public.finance_v3_profiles (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null references auth.users(id) on delete restrict,
  name text not null check (char_length(name) between 1 and 80),
  profile_type text not null default 'personal' check (profile_type in ('personal','household')),
  encryption_salt text not null check (char_length(encryption_salt) between 8 and 200),
  encryption_check jsonb not null,
  kdf_iterations integer not null default 310000 check (kdf_iterations between 100000 and 2000000),
  cloud_schema_version integer not null default 3 check (cloud_schema_version = 3),
  min_app_version_code integer not null default 130000 check (min_app_version_code >= 130000),
  current_audit_id bigint not null default 0 check (current_audit_id >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.finance_v3_members (
  profile_id uuid not null references public.finance_v3_profiles(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('owner','editor','viewer')),
  invited_by uuid references auth.users(id) on delete set null,
  joined_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (profile_id,user_id)
);

create unique index if not exists finance_v3_one_owner_idx
  on public.finance_v3_members(profile_id) where role='owner';

create table if not exists public.finance_v3_records (
  profile_id uuid not null references public.finance_v3_profiles(id) on delete cascade,
  collection text not null check (char_length(collection) between 1 and 60),
  record_id text not null check (char_length(record_id) between 1 and 240),
  payload jsonb not null check (payload ? '__financeEncrypted'),
  sort_index integer not null default 0,
  revision bigint not null default 1 check (revision > 0),
  deleted_at timestamptz,
  updated_at timestamptz not null default now(),
  updated_by_user uuid not null references auth.users(id) on delete restrict,
  updated_by_device text not null default '',
  app_version text not null default '',
  app_version_code integer not null default 130000,
  min_writer_version_code integer not null default 130000,
  finance_schema_version integer not null default 12,
  primary key (profile_id,collection,record_id)
);

create table if not exists public.finance_v3_batches (
  profile_id uuid not null references public.finance_v3_profiles(id) on delete cascade,
  batch_id text not null check (char_length(batch_id) between 1 and 180),
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  device_id text not null default '',
  status text not null default 'processing' check (status in ('processing','committed','conflict','rejected')),
  result jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  committed_at timestamptz,
  primary key (profile_id,batch_id)
);

create table if not exists public.finance_v3_audit (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.finance_v3_profiles(id) on delete cascade,
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  batch_id text not null,
  collection text not null,
  record_id text not null,
  action text not null check (action in ('upsert','delete','restore')),
  revision bigint not null,
  payload jsonb not null,
  sort_index integer not null default 0,
  deleted_at timestamptz,
  device_id text not null default '',
  app_version text not null default '',
  app_version_code integer not null default 130000,
  created_at timestamptz not null default now(),
  constraint finance_v3_audit_once unique (profile_id,batch_id,collection,record_id)
);

create table if not exists public.finance_v3_devices (
  profile_id uuid not null references public.finance_v3_profiles(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  device_id text not null check (char_length(device_id) between 1 and 160),
  device_name text not null default 'Device',
  platform text not null default '',
  app_version text not null default '',
  app_version_code integer not null default 0,
  cloud_schema_version integer not null default 3,
  last_pull_audit_id bigint not null default 0,
  last_seen_at timestamptz not null default now(),
  last_sync_at timestamptz,
  last_push_at timestamptz,
  revoked_at timestamptz,
  revoked_by_user uuid references auth.users(id) on delete set null,
  revoked_by_device text not null default '',
  primary key (profile_id,user_id,device_id)
);

create table if not exists public.finance_v3_payment_operations (
  profile_id uuid not null references public.finance_v3_profiles(id) on delete cascade,
  operation_id text not null,
  expense_id text not null,
  operation_type text not null check (operation_type in ('expense_payment','gym_auto_payment','expense_payment_restore')),
  actor_user_id uuid not null references auth.users(id) on delete restrict,
  account_name text not null default '',
  amount numeric(18,2) not null default 0 check (amount >= 0),
  device_id text not null default '',
  app_version text not null default '',
  created_at timestamptz not null default now(),
  payload jsonb not null default '{}'::jsonb,
  primary key (profile_id,operation_id,expense_id,operation_type)
);

create table if not exists public.finance_v3_invites (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.finance_v3_profiles(id) on delete cascade,
  token_hash text not null unique check (char_length(token_hash)=64),
  role text not null check (role in ('editor','viewer')),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null,
  accepted_at timestamptz,
  accepted_by uuid references auth.users(id) on delete set null,
  revoked_at timestamptz
);

create table if not exists public.finance_v3_restore_points (
  id uuid primary key default gen_random_uuid(),
  profile_id uuid not null references public.finance_v3_profiles(id) on delete cascade,
  label text not null check (char_length(label) between 1 and 120),
  encrypted_snapshot jsonb not null check (encrypted_snapshot ? '__financeEncrypted'),
  encryption_record_id text not null,
  summary jsonb not null default '{}'::jsonb,
  created_by uuid not null references auth.users(id) on delete restrict,
  created_at timestamptz not null default now()
);

create index if not exists finance_v3_records_collection_idx on public.finance_v3_records(profile_id,collection,deleted_at,sort_index);
create index if not exists finance_v3_records_updated_idx on public.finance_v3_records(profile_id,updated_at desc);
create index if not exists finance_v3_audit_cursor_idx on public.finance_v3_audit(profile_id,id);
create index if not exists finance_v3_devices_active_idx on public.finance_v3_devices(profile_id,revoked_at,last_seen_at desc);
create index if not exists finance_v3_invites_profile_idx on public.finance_v3_invites(profile_id,expires_at desc);
create index if not exists finance_v3_restore_points_profile_idx on public.finance_v3_restore_points(profile_id,created_at desc);

create or replace function public.finance_v3_role(p_profile_id uuid)
returns text
language sql
stable
security definer
set search_path=''
as $$
  select m.role
  from public.finance_v3_members m
  where m.profile_id=p_profile_id and m.user_id=(select auth.uid())
$$;

create or replace function public.finance_v3_require_member(p_profile_id uuid, p_write boolean default false)
returns text
language plpgsql
stable
security definer
set search_path=''
as $$
declare v_role text;
begin
  if auth.uid() is null then raise exception 'authentication_required'; end if;
  select public.finance_v3_role(p_profile_id) into v_role;
  if v_role is null then raise exception 'profile_access_denied'; end if;
  if p_write and v_role not in ('owner','editor') then raise exception 'profile_read_only'; end if;
  return v_role;
end;
$$;

create or replace function public.finance_v3_list_profiles()
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_profiles jsonb;
begin
  if v_uid is null then raise exception 'authentication_required'; end if;
  select coalesce(jsonb_agg(jsonb_build_object(
    'profile_id',p.id,'name',p.name,'profile_type',p.profile_type,'role',m.role,
    'encryption_salt',p.encryption_salt,'encryption_check',p.encryption_check,
    'kdf_iterations',p.kdf_iterations,'cloud_schema_version',p.cloud_schema_version,
    'min_app_version_code',p.min_app_version_code,'created_at',p.created_at,'updated_at',p.updated_at
  ) order by p.updated_at desc),'[]'::jsonb)
  into v_profiles
  from public.finance_v3_members m
  join public.finance_v3_profiles p on p.id=m.profile_id
  where m.user_id=v_uid;
  return jsonb_build_object('profiles',v_profiles);
end;
$$;

create or replace function public.finance_v3_create_profile(
  p_name text,
  p_profile_type text,
  p_encryption_salt text,
  p_encryption_check jsonb,
  p_kdf_iterations integer,
  p_min_app_version_code integer default 130000
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_profile public.finance_v3_profiles%rowtype;
begin
  if v_uid is null then raise exception 'authentication_required'; end if;
  if coalesce(length(trim(p_name)),0)=0 then raise exception 'profile_name_required'; end if;
  if p_profile_type not in ('personal','household') then raise exception 'invalid_profile_type'; end if;
  if not coalesce(p_encryption_check ? '__financeEncrypted',false) then raise exception 'encrypted_key_check_required'; end if;
  insert into public.finance_v3_profiles(owner_user_id,name,profile_type,encryption_salt,encryption_check,kdf_iterations,min_app_version_code)
  values(v_uid,left(trim(p_name),80),p_profile_type,left(p_encryption_salt,200),p_encryption_check,greatest(100000,least(coalesce(p_kdf_iterations,310000),2000000)),greatest(coalesce(p_min_app_version_code,130000),130000))
  returning * into v_profile;
  insert into public.finance_v3_members(profile_id,user_id,role,invited_by) values(v_profile.id,v_uid,'owner',v_uid);
  return jsonb_build_object('profile_id',v_profile.id,'name',v_profile.name,'profile_type',v_profile.profile_type,'role','owner');
end;
$$;

create or replace function public.finance_v3_create_invite(p_profile_id uuid,p_token_hash text,p_role text,p_expires_hours integer default 72)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_id uuid; v_role text;
begin
  v_role:=public.finance_v3_require_member(p_profile_id,false);
  if v_role<>'owner' then raise exception 'owner_required'; end if;
  if p_role not in ('editor','viewer') then raise exception 'invalid_invite_role'; end if;
  if coalesce(length(p_token_hash),0)<>64 then raise exception 'invalid_invite_token'; end if;
  insert into public.finance_v3_invites(profile_id,token_hash,role,created_by,expires_at)
  values(p_profile_id,lower(p_token_hash),p_role,v_uid,now()+make_interval(hours=>greatest(1,least(coalesce(p_expires_hours,72),168))))
  returning id into v_id;
  return jsonb_build_object('invite_id',v_id,'role',p_role,'expires_at',(select expires_at from public.finance_v3_invites where id=v_id));
end;
$$;

create or replace function public.finance_v3_accept_invite(p_token_hash text)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_uid uuid:=auth.uid(); v_invite public.finance_v3_invites%rowtype; v_profile public.finance_v3_profiles%rowtype;
begin
  if v_uid is null then raise exception 'authentication_required'; end if;
  select * into v_invite from public.finance_v3_invites
   where token_hash=lower(p_token_hash) and accepted_at is null and revoked_at is null and expires_at>now()
   for update;
  if not found then raise exception 'invite_invalid_or_expired'; end if;
  insert into public.finance_v3_members(profile_id,user_id,role,invited_by)
  values(v_invite.profile_id,v_uid,v_invite.role,v_invite.created_by)
  on conflict(profile_id,user_id) do update set
    role=case when public.finance_v3_members.role='owner' then 'owner' else excluded.role end,
    invited_by=case when public.finance_v3_members.role='owner' then public.finance_v3_members.invited_by else excluded.invited_by end,
    updated_at=now();
  update public.finance_v3_invites set accepted_at=now(),accepted_by=v_uid where id=v_invite.id;
  select * into v_profile from public.finance_v3_profiles where id=v_invite.profile_id;
  return jsonb_build_object(
    'profile_id',v_profile.id,'name',v_profile.name,'profile_type',v_profile.profile_type,
    'role',(select role from public.finance_v3_members where profile_id=v_invite.profile_id and user_id=v_uid),
    'encryption_salt',v_profile.encryption_salt,'encryption_check',v_profile.encryption_check,'kdf_iterations',v_profile.kdf_iterations
  );
end;
$$;

create or replace function public.finance_v3_list_members(p_profile_id uuid)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_role text; v_members jsonb;
begin
  v_role:=public.finance_v3_require_member(p_profile_id,false);
  select coalesce(jsonb_agg(jsonb_build_object('user_id',m.user_id,'email',u.email,'role',m.role,'joined_at',m.joined_at) order by case m.role when 'owner' then 1 when 'editor' then 2 else 3 end,u.email),'[]'::jsonb)
  into v_members
  from public.finance_v3_members m join auth.users u on u.id=m.user_id
  where m.profile_id=p_profile_id;
  return jsonb_build_object('members',v_members,'current_role',v_role);
end;
$$;

create or replace function public.finance_v3_set_member_role(p_profile_id uuid,p_member_user_id uuid,p_role text)
returns jsonb
language plpgsql
