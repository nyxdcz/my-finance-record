create policy "finance v3 restore member read" on public.finance_v3_restore_points for select to authenticated using (public.finance_v3_role(profile_id) is not null);

-- The membership helper is used by RLS policies, so authenticated users need EXECUTE.
-- It reveals only the caller's own role (or null) for the supplied profile ID.
revoke execute on function public.finance_v3_role(uuid) from public,anon;
grant execute on function public.finance_v3_role(uuid) to authenticated;
revoke execute on function public.finance_v3_require_member(uuid,boolean) from public,anon,authenticated;

-- RPC execution grants.
do $$
declare r record;
begin
  for r in select p.oid::regprocedure as signature from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname like 'finance_v3_%' and p.proname not in ('finance_v3_role','finance_v3_require_member') loop
    execute format('revoke execute on function %s from public,anon',r.signature);
    execute format('grant execute on function %s to authenticated',r.signature);
  end loop;
end $$;

