create table if not exists public.finance_sync_profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  cloud_schema_version integer not null default 2 check (cloud_schema_version >= 2),
  current_audit_id bigint not null default 0 check (current_audit_id >= 0),
  min_app_version_code integer not null default 120210 check (min_app_version_code > 0),
  migrated_from_v1 boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.finance_sync_records (
  user_id uuid not null references auth.users(id) on delete cascade,
  collection text not null check (char_length(collection) between 1 and 60),
  record_id text not null check (char_length(record_id) between 1 and 240),
  payload jsonb not null default '{}'::jsonb,
  sort_index integer not null default 0,
  revision bigint not null default 1 check (revision > 0),
  deleted_at timestamptz,
  updated_at timestamptz not null default now(),
  updated_by_device text not null default '',
  app_version text not null default '',
  app_version_code integer not null default 120210,
  min_writer_version_code integer not null default 120210,
  schema_version integer not null default 12,
  primary key (user_id, collection, record_id)
);

create table if not exists public.finance_sync_batches (
  user_id uuid not null references auth.users(id) on delete cascade,
  batch_id text not null check (char_length(batch_id) between 1 and 180),
  device_id text not null default '',
  status text not null default 'processing' check (status in ('processing','committed','conflict','rejected')),
  result jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  committed_at timestamptz,
  primary key (user_id, batch_id)
);

create table if not exists public.finance_sync_audit (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  batch_id text not null,
  collection text not null,
  record_id text not null,
  action text not null check (action in ('upsert','delete')),
  revision bigint not null,
  payload jsonb not null default '{}'::jsonb,
  sort_index integer not null default 0,
  deleted_at timestamptz,
  device_id text not null default '',
  app_version text not null default '',
  app_version_code integer not null default 120210,
  created_at timestamptz not null default now(),
  constraint finance_sync_audit_once unique (user_id, batch_id, collection, record_id)
);

alter table public.finance_cloud_devices
  add column if not exists app_version_code integer not null default 0,
  add column if not exists cloud_schema_version integer not null default 1,
  add column if not exists last_pull_audit_id bigint not null default 0,
  add column if not exists last_push_at timestamptz,
  add column if not exists revoked_at timestamptz,
  add column if not exists revoked_by_device text not null default '';

create index if not exists finance_sync_records_updated_idx
  on public.finance_sync_records(user_id, updated_at desc);
create index if not exists finance_sync_records_collection_idx
  on public.finance_sync_records(user_id, collection, deleted_at, sort_index);
create index if not exists finance_sync_audit_user_cursor_idx
  on public.finance_sync_audit(user_id, id);
create index if not exists finance_sync_batches_created_idx
  on public.finance_sync_batches(user_id, created_at desc);
create index if not exists finance_cloud_devices_active_idx
  on public.finance_cloud_devices(user_id, revoked_at, last_seen_at desc);

create or replace function public.finance_jsonb_deep_merge(original jsonb, incoming jsonb)
returns jsonb
language sql
immutable
parallel safe
as $$
  select case
    when jsonb_typeof(coalesce(original, '{}'::jsonb)) = 'object'
     and jsonb_typeof(coalesce(incoming, '{}'::jsonb)) = 'object'
    then coalesce((
      select jsonb_object_agg(key, value)
      from (
        select key,
          case
            when original ? key and incoming ? key
              then public.finance_jsonb_deep_merge(original -> key, incoming -> key)
            when incoming ? key then incoming -> key
            else original -> key
          end as value
        from (
          select jsonb_object_keys(coalesce(original, '{}'::jsonb)) as key
          union
          select jsonb_object_keys(coalesce(incoming, '{}'::jsonb)) as key
        ) keys
      ) merged
    ), '{}'::jsonb)
    else coalesce(incoming, original, 'null'::jsonb)
  end;
$$;

create or replace function public.finance_sync_register_device(
  p_device_id text,
  p_device_name text,
  p_platform text,
  p_app_version text,
  p_app_version_code integer,
  p_last_pull_audit_id bigint default 0
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid uuid := auth.uid();
  v_existing public.finance_cloud_devices%rowtype;
begin
  if v_uid is null then raise exception 'authentication_required'; end if;
  if coalesce(length(trim(p_device_id)), 0) = 0 then raise exception 'device_id_required'; end if;

  select * into v_existing
  from public.finance_cloud_devices
  where user_id = v_uid and device_id = p_device_id;

  if found and v_existing.revoked_at is not null then
    return jsonb_build_object(
      'status','revoked',
      'revoked_at',v_existing.revoked_at,
      'device_id',p_device_id
    );
  end if;

  insert into public.finance_cloud_devices (
    user_id, device_id, device_name, platform, app_version, app_version_code,
    cloud_schema_version, last_seen_at, last_pull_audit_id
  ) values (
    v_uid, left(trim(p_device_id), 160), left(coalesce(nullif(trim(p_device_name),''),'Device'), 80),
    left(coalesce(p_platform,''), 300), left(coalesce(p_app_version,''), 40),
    greatest(coalesce(p_app_version_code,0),0), 2, now(), greatest(coalesce(p_last_pull_audit_id,0),0)
  )
  on conflict (user_id, device_id) do update set
    device_name = excluded.device_name,
    platform = excluded.platform,
    app_version = excluded.app_version,
    app_version_code = excluded.app_version_code,
    cloud_schema_version = 2,
    last_seen_at = now(),
    last_pull_audit_id = greatest(public.finance_cloud_devices.last_pull_audit_id, excluded.last_pull_audit_id);

  return jsonb_build_object('status','active','device_id',p_device_id);
end;
$$;

