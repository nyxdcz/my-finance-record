  if v_uid is null then raise exception 'authentication_required'; end if;
  if p_operation_type not in ('expense_payment','gym_auto_payment','expense_payment_restore') then
    raise exception 'invalid_financial_operation';
  end if;

  return public.finance_sync_commit_financial_operations(
    'financial:' || left(coalesce(p_operation_id,''),110) || ':' || pg_catalog.md5(coalesce(p_changes,'[]'::jsonb)::text),
    jsonb_build_array(jsonb_build_object(
      'operation_id',p_operation_id,'operation_type',p_operation_type,'expense_id',p_expense_id,
      'account_name',p_account_name,'amount',p_amount
    )),
    p_device_id,p_app_version,p_app_version_code,p_changes
  );
end;
$$;

